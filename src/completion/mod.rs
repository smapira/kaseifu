//! Shell completion generation, installation, and best-effort upkeep.
//!
//! `kaseifu completions <shell>` prints a script; `completions zsh --install`
//! writes the zsh file into the first writable completion directory. Every
//! command run also refreshes the installed zsh script when it is missing or
//! stale — best effort only: a failed refresh must never change kaseifu's exit
//! code or output (stderr is touched only with `KASEIFU_DEBUG=1`).
//!
//! Directory detection order: `--dir`, `KASEIFU_COMPLETION_DIR`, then the
//! Homebrew / Prezto / XDG / user candidates (see [`candidates`]). An explicit
//! choice is never silently replaced by a fallback. A non-empty
//! `KASEIFU_NO_COMPLETION_UPDATE` disables the automatic update.

mod zsh;

use std::ffi::OsString;
use std::io;
use std::path::{Path, PathBuf};

/// Installed zsh completion file name (also the `#compdef` target).
pub const FILE_NAME: &str = "_kaseifu";

/// Directory override used by installation and by the automatic update.
pub const ENV_DIR: &str = "KASEIFU_COMPLETION_DIR";

/// Non-empty value disables the automatic update.
pub const ENV_DISABLE: &str = "KASEIFU_NO_COMPLETION_UPDATE";

/// First line of the version marker written into the zsh script.
const MARKER_PREFIX: &str = "# kaseifu completions v";

/// Result of writing the completion file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WriteOutcome {
    /// The file content changed and was replaced.
    Written,
    /// The file already had the exact content (idempotent no-op).
    Unchanged,
}

/// State of the installed zsh completion file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    /// Present and generated by the current version.
    Installed,
    /// Present but generated by a different version.
    Stale,
    /// Not present (or unreadable).
    Missing,
}

/// Why no completion directory could be used for `--install`.
#[derive(Debug, thiserror::Error)]
pub enum DirError {
    /// An explicitly chosen directory cannot be written to.
    #[error("{source_name} is not a writable directory: {path}")]
    Unusable {
        /// `--dir` or `KASEIFU_COMPLETION_DIR`.
        source_name: &'static str,
        /// The rejected path.
        path: String,
    },
    /// No default candidate exists and is writable.
    #[error("no writable zsh completion directory found (pass --dir or set {ENV_DIR})")]
    NoneFound,
}

/// Version marker of the script generated by this build.
pub fn marker() -> String {
    format!("{MARKER_PREFIX}{}", current_version())
}

/// Version of this build, as recorded in the marker.
pub fn current_version() -> &'static str {
    env!("CARGO_PKG_VERSION")
}

/// Render the completion script for `shell`.
///
/// The zsh script carries the version marker and never offers hidden commands
/// (see [`zsh`](self)); other shells are emitted as `clap_complete` generates
/// them.
pub fn render(shell: clap_complete::Shell, cmd: &mut clap::Command) -> Vec<u8> {
    let name = cmd.get_name().to_string();
    let mut buffer = Vec::new();
    clap_complete::generate(shell, cmd, name, &mut buffer);
    if shell != clap_complete::Shell::Zsh {
        return buffer;
    }
    let text = String::from_utf8_lossy(&buffer).into_owned();
    let stripped = zsh::strip_hidden(&text, &zsh::hidden_labels(cmd));
    zsh::with_marker(stripped, &marker()).into_bytes()
}

/// Directories searched for the zsh completion file, in priority order.
///
/// `home` and `xdg_data_home` are injected so tests never read the process
/// environment; `XDG_DATA_HOME` is read directly because `dirs::data_dir()`
/// points at `~/Library/Application Support` on macOS.
pub fn candidates(home: Option<&Path>, xdg_data_home: Option<&Path>) -> Vec<PathBuf> {
    let mut dirs = vec![
        PathBuf::from("/opt/homebrew/share/zsh/site-functions"),
        PathBuf::from("/usr/local/share/zsh/site-functions"),
    ];
    if let Some(home) = home {
        dirs.push(home.join(".zprezto/modules/completion/external/src"));
    }
    let data_home = xdg_data_home
        .map(Path::to_path_buf)
        .or_else(|| home.map(|home| home.join(".local/share")));
    if let Some(data_home) = data_home {
        dirs.push(data_home.join("zsh/site-functions"));
    }
    if let Some(home) = home {
        dirs.push(home.join(".zsh/completions"));
    }
    dirs
}

/// Candidate list for this user environment.
pub fn default_candidates() -> Vec<PathBuf> {
    let home = dirs::home_dir();
    let xdg = std::env::var_os("XDG_DATA_HOME")
        .filter(|value| !value.is_empty())
        .map(PathBuf::from);
    candidates(home.as_deref(), xdg.as_deref())
}

/// First candidate that exists and can be written to.
pub fn detect(candidates: &[PathBuf]) -> Option<PathBuf> {
    candidates.iter().find(|dir| usable(dir)).cloned()
}

fn usable(dir: &Path) -> bool {
    std::fs::metadata(dir)
        .map(|meta| meta.is_dir() && !meta.permissions().readonly())
        .unwrap_or(false)
}

fn non_empty(value: Option<OsString>) -> Option<OsString> {
    value.filter(|value| !value.is_empty())
}

fn env_path(name: &str) -> Option<PathBuf> {
    non_empty(std::env::var_os(name)).map(PathBuf::from)
}

/// State of the completion file inside one directory.
pub fn status_in(dir: &Path) -> Status {
    let Ok(bytes) = std::fs::read(dir.join(FILE_NAME)) else {
        return Status::Missing;
    };
    let text = String::from_utf8_lossy(&bytes);
    if text.lines().any(|line| line.trim() == marker()) {
        Status::Installed
    } else {
        Status::Stale
    }
}

/// Version recorded in the installed marker, when a script is present.
pub fn installed_version(dir: &Path) -> Option<String> {
    let content = std::fs::read_to_string(dir.join(FILE_NAME)).ok()?;
    content
        .lines()
        .find_map(|line| line.trim().strip_prefix(MARKER_PREFIX))
        .map(str::to_string)
}

/// Completion state and the directory it refers to (used by `doctor`).
pub fn state() -> (Status, Option<PathBuf>) {
    let candidates = match env_path(ENV_DIR) {
        Some(explicit) => vec![explicit],
        None => default_candidates(),
    };
    for dir in &candidates {
        if dir.join(FILE_NAME).is_file() {
            return (status_in(dir), Some(dir.clone()));
        }
    }
    (Status::Missing, detect(&candidates))
}

/// Resolve the directory `completions zsh --install` writes to.
pub fn install_dir(explicit: Option<&Path>) -> Result<PathBuf, DirError> {
    if let Some(dir) = explicit {
        return check_explicit(dir, "--dir");
    }
    if let Some(dir) = env_path(ENV_DIR) {
        return check_explicit(&dir, ENV_DIR);
    }
    detect(&default_candidates()).ok_or(DirError::NoneFound)
}

fn check_explicit(dir: &Path, source_name: &'static str) -> Result<PathBuf, DirError> {
    if usable(dir) {
        return Ok(dir.to_path_buf());
    }
    Err(DirError::Unusable {
        source_name,
        path: dir.display().to_string(),
    })
}

/// Write the zsh script into `dir` unless the file already has those bytes.
pub fn install(dir: &Path, cmd: &mut clap::Command) -> io::Result<WriteOutcome> {
    let script = render(clap_complete::Shell::Zsh, cmd);
    write_if_changed(dir, &script)
}

/// Write `script` atomically (sibling temp file plus rename) when it differs.
pub fn write_if_changed(dir: &Path, script: &[u8]) -> io::Result<WriteOutcome> {
    let target = dir.join(FILE_NAME);
    if std::fs::read(&target).is_ok_and(|existing| existing == script) {
        return Ok(WriteOutcome::Unchanged);
    }
    let temp = temp_path(dir);
    std::fs::write(&temp, script)?;
    if let Err(error) = std::fs::rename(&temp, &target) {
        let _ = std::fs::remove_file(&temp);
        return Err(error);
    }
    Ok(WriteOutcome::Written)
}

/// Sibling temporary file name.
///
/// Dot-prefixed so compinit never reads it, following the
/// `config::loader` convention of `<sibling>.<pid>` temp files.
fn temp_path(dir: &Path) -> PathBuf {
    dir.join(format!(".{FILE_NAME}.tmp-{}", std::process::id()))
}

/// Inputs for the automatic update.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RefreshPlan {
    /// Directories that may receive the regenerated script, in order.
    pub candidates: Vec<PathBuf>,
    /// False disables the update entirely.
    pub enabled: bool,
}

impl RefreshPlan {
    /// Read the plan from the process environment.
    pub fn from_env() -> Self {
        let candidates = match env_path(ENV_DIR) {
            Some(explicit) => vec![explicit],
            None => default_candidates(),
        };
        Self {
            candidates,
            enabled: non_empty(std::env::var_os(ENV_DISABLE)).is_none(),
        }
    }
}

/// Regenerate the installed zsh script when it is missing or stale.
///
/// Best effort: no error escapes and nothing is printed unless
/// `KASEIFU_DEBUG=1` is set, so a failed refresh never perturbs the command
/// that triggered it.
pub fn refresh(cmd: &mut clap::Command, plan: &RefreshPlan) {
    if !plan.enabled {
        crate::debug!("completion refresh disabled via {ENV_DISABLE}");
        return;
    }
    let Some(dir) = detect(&plan.candidates) else {
        crate::debug!("completion refresh skipped: no writable directory");
        return;
    };
    if let Err(error) = refresh_dir(&dir, cmd) {
        crate::debug!("completion refresh failed for {}: {error}", dir.display());
    }
}

/// Convenience wrapper used by `main`.
pub fn refresh_if_stale(cmd: &mut clap::Command) {
    refresh(cmd, &RefreshPlan::from_env());
}

fn refresh_dir(dir: &Path, cmd: &mut clap::Command) -> io::Result<WriteOutcome> {
    let target = dir.join(FILE_NAME);
    if target
        .symlink_metadata()
        .is_ok_and(|meta| meta.file_type().is_symlink())
    {
        // A user-managed link (dotfiles, a package manager): never replace it
        // silently; `--install` stays the explicit override.
        return Ok(WriteOutcome::Unchanged);
    }
    if status_in(dir) == Status::Installed {
        return Ok(WriteOutcome::Unchanged);
    }
    install(dir, cmd)
}
